#!/usr/bin/env python3
"""
Turns the Bundeslebensmittelschlüssel (BLS 4.0) spreadsheet into src/lib/blsData.ts.

  pip install openpyxl
  python3 scripts/import_bls.py BLS_4_0_Daten_2025_DE.xlsx

The BLS is published by the Max Rubner-Institut under CC BY 4.0 (https://blsdb.de).
Columns: A "BLS Code", B "Lebensmittelbezeichnung", C "Food name", then three columns per
nutrient ("<CODE> <name> [<unit>/100g]", "<CODE> Datenherkunft", "<CODE> Referenz").
Only the nutrients the app shows are kept, which keeps the bundled file small.
"""
import json
import re
import sys

from openpyxl import load_workbook

# EuroFIR component code -> field in the app's Nutrients type
WANTED = {
    'ENERCC': 'kcal',
    'PROT625': 'protein',
    'CHO': 'carbs',
    'FAT': 'fat',
    'SUGAR': 'sugar',
    'FIBT': 'fiber',
    'FASAT': 'satFat',
    'NACL': 'salt',
    'NA': 'sodium_mg',  # used for salt when NACL is missing (salt = Na × 2.5)
    'ENERCJ': 'kj',  # fallback for kcal
}
ORDER = ['kcal', 'protein', 'carbs', 'fat', 'fiber', 'sugar', 'satFat', 'salt']


def num(v):
    if v is None:
        return None
    if isinstance(v, (int, float)):
        return float(v)
    s = str(v).strip().replace(',', '.')
    if s in ('', '-', 'n.a.', 'na', 'NA'):
        return None
    try:
        return float(s)
    except ValueError:
        return None


def unit_of(header):
    m = re.search(r'\[([^\]/]+)/100\s*g\]', header) or re.search(r'\(([^)/]+)/100\s*g\)', header)
    return m.group(1).strip() if m else ''


def scale(value, unit, target):
    """Converts mg/µg values to grams where the app expects grams."""
    if value is None:
        return None
    u = unit.lower().replace('μ', 'µ')
    if target == 'sodium_mg':
        return value / 1000 if u == 'µg' else value * 1000 if u == 'g' else value
    if target in ('kcal', 'kj'):
        return value
    if u == 'mg':
        return value / 1000
    if u == 'µg':
        return value / 1_000_000
    return value


def main(path, out='src/lib/blsData.ts'):
    wb = load_workbook(path, read_only=True, data_only=True)
    ws = wb.worksheets[0]
    rows = ws.iter_rows(values_only=True)
    header = [str(h or '').strip() for h in next(rows)]

    def find(prefixes):
        for i, h in enumerate(header):
            if any(h.lower().startswith(p.lower()) for p in prefixes):
                return i
        raise SystemExit(f'column not found: {prefixes}')

    i_code = find(['BLS Code', 'BLS-Code', 'SBLS'])
    i_de = find(['Lebensmittelbezeichnung'])
    i_en = find(['Food name'])
    cols = {}
    for i, h in enumerate(header):
        m = re.match(r'^([A-Z0-9]+)\s+(.*)$', h)
        if not m:
            continue
        code, rest = m.group(1), m.group(2)
        if code in WANTED and not rest.startswith(('Datenherkunft', 'Referenz')) and code not in cols:
            cols[code] = (i, unit_of(h))
    missing = [c for c in ('PROT625', 'CHO', 'FAT') if c not in cols]
    if missing or ('ENERCC' not in cols and 'ENERCJ' not in cols):
        raise SystemExit(f'nutrient columns not found: {missing or "ENERCC/ENERCJ"}; headers start with {header[:8]}')

    foods = []
    skipped = 0
    for r in rows:
        code = str(r[i_code] or '').strip()
        de = str(r[i_de] or '').strip()
        en = str(r[i_en] or '').strip()
        if not code or not de:
            continue
        v = {}
        for c, (i, unit) in cols.items():
            v[WANTED[c]] = scale(num(r[i]), unit, WANTED[c])
        if v.get('kcal') is None and v.get('kj') is not None:
            v['kcal'] = v['kj'] / 4.184
        if v.get('salt') is None and v.get('sodium_mg') is not None:
            v['salt'] = v['sodium_mg'] * 2.5 / 1000
        if v.get('kcal') is None:
            skipped += 1
            continue
        row = [code, de, en or de]
        for k in ORDER:
            x = v.get(k)
            row.append(None if x is None else round(x, 1 if k == 'kcal' else 2))
        # trailing missing optional values can go
        while row[-1] is None:
            row.pop()
        foods.append(row)

    foods.sort(key=lambda f: f[0])
    body = '\n'.join(json.dumps(f, ensure_ascii=False, separators=(',', ':')) + ',' for f in foods)
    with open(out, 'w', encoding='utf-8') as fh:
        fh.write(
            '/* Generated by scripts/import_bls.py from BLS_4_0_Daten_2025_DE.xlsx. Do not edit by hand.\n'
            ' * Bundeslebensmittelschlüssel (BLS) 4.0 — Max Rubner-Institut, Karlsruhe, CC BY 4.0,\n'
            ' * https://doi.org/10.25826/Data20251217-134202-0\n'
            ' * Row: code, German name, English name, kcal, protein, carbs, fat, fiber, sugar, satFat, salt (per 100 g; null = not given).\n'
            ' */\n'
            'export type BlsRow = [string, string, string, number, ...(number | null)[]];\n\n'
            f'export const BLS_VERSION = \'4.0\';\n\n'
            'export const BLS_ROWS: BlsRow[] = [\n'
            + body
            + '\n];\n'
        )
    print(f'{len(foods)} foods written to {out} ({skipped} without energy skipped); columns: {sorted(cols)}')


if __name__ == '__main__':
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    main(*sys.argv[1:])
